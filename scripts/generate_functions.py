"""Generate src/pythonic_dax/_functions.py from the DAX function specs.

Run after changing _specs.py:  python scripts/generate_functions.py
A test fails if the generated file is out of date.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from pythonic_dax._coverage import PLANNED  # noqa: E402
from pythonic_dax._specs import SPECS, Param  # noqa: E402

TARGET = ROOT / "src" / "pythonic_dax" / "_functions.py"

ANNOTATION = {
    "S": "ScalarArg",
    "T": "TableArg",
    "C": "Column",
    "TC": "TableOrColumnArg",
    "F": "FilterArg",
    "D": "DatesArg",
    "K": "KeywordArg",
    "A": "AnyArg",
}
RETURNS = {"S": "Expr", "T": "TableExpr", "M": "ModifierExpr"}

HEADER = '''"""DAX functions as Python functions. GENERATED by scripts/generate_functions.py.

Do not edit by hand: change _specs.py and run the script.

Each function builds an expression; nothing is computed until the model evaluates it.
"""

# ruff: noqa: E501

from __future__ import annotations

import datetime as dt
from collections.abc import Callable
from decimal import Decimal
from typing import TYPE_CHECKING, Any, TypeVar, Union

from ._build import build
from .expr import OMITTED, Expr, Keyword, ModifierExpr, TableExpr, _Omitted

if TYPE_CHECKING:
    from .objects import Column

ScalarArg = Union[Expr, TableExpr, int, float, str, bool, Decimal, dt.date, None]
TableArg = Union[TableExpr, list[Any]]
TableOrColumnArg = Union["Column", TableExpr]
FilterArg = Union[Expr, TableExpr, ModifierExpr, list[Any]]
DatesArg = Union["Column", TableExpr, list[Any]]
KeywordArg = Union[str, Keyword, Callable[..., Any]]
AnyArg = Union[Expr, TableExpr, list[Any], int, float, str, bool, None]

_F = TypeVar("_F", bound=Callable[..., Any])


def _dax_function(name: str) -> Callable[[_F], _F]:
    def mark(fn: _F) -> _F:
        fn._dax_name = name  # type: ignore[attr-defined]
        return fn

    return mark

'''


def param_text(p: Param) -> str:
    ann = ANNOTATION[p.kind]
    if p.kind == "C":
        ann = "Column"
    if p.repeat:
        return f"*{p.python_name}: {ann}"
    if p.optional:
        return f"{p.python_name}: {ann} | _Omitted = OMITTED"
    return f"{p.python_name}: {ann}"


def value_text(p: Param) -> str:
    return p.python_name


def main() -> None:
    out = [HEADER]
    names = sorted(SPECS)
    for name in names:
        spec = SPECS[name]
        params = ", ".join(param_text(p) for p in spec.params)
        values = ", ".join(value_text(p) for p in spec.params)
        phase = PLANNED.get(name)
        when = f"Evaluated from Phase {phase}." if phase else ""
        doc = f'    """DAX ``{spec.signature}``\n\n    {spec.summary}\n\n    {when}\n    """'
        out.append(
            f'\n@_dax_function("{name}")\n'
            f"def {name}({params}) -> {RETURNS[spec.returns]}:\n"
            f"{doc}\n"
            f'    return build("{name}", [{values}])  # type: ignore[return-value]\n'
        )
    out.append("\n__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n")
    text = "\n".join(out).replace("\n\n\n\n", "\n\n\n")
    text = subprocess.run(
        ["ruff", "format", "--stdin-filename", str(TARGET), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            sys.exit(f"{TARGET} is out of date: run python scripts/generate_functions.py")
        return
    TARGET.write_text(text)


if __name__ == "__main__":
    main()
